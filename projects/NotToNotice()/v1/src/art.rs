pub fn glyph(ch: char) -> Option<&'static [&'static str; 5]> {
    let needle: String = ch.to_string();
    FONT.iter()
        .find(|(k, _)| *k == needle)
        .map(|(_, rows)| rows)
}

/// Big 5-row pixel text. `scale` = cells per font pixel. Returns width used.
pub fn big_text(g: &mut Grid, x0: i64, y0: i64, s: &str, fg: Color, scale: i64, alpha: f64) -> i64 {
    let mut x = x0;
    for ch in s.chars() {
        if let Some(rows) = glyph(ch) {
            let gw = rows[0].chars().count() as i64;
            for (ry, row) in rows.iter().enumerate() {
                for (rx, pc) in row.chars().enumerate() {
                    if pc != '#' {
                        continue;
                    }
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = x + rx as i64 * scale + sx;
                            let py = y0 + ry as i64 * scale + sy;
                            if alpha >= 1.0 {
                                g.put_bold(px, py, '█', fg);
                            } else {
                                g.put_alpha(px, py, '█', fg, alpha);
                            }
                        }
                    }
                }
            }
            x += gw * scale;
        }
    }
    x
}

pub fn big_text_width(s: &str, scale: i64) -> i64 {
    s.chars()
        .map(|c| glyph(c).map(|r| r[0].chars().count() as i64).unwrap_or(2))
        .sum::<i64>()
        * scale
}

// ---------------------------------------------------------------- sprites ---

pub struct Sprite {
    pub rows: &'static [&'static str],
    /// char -> color (hex). Unmapped chars are skipped (transparent).
    pub pal: &'static [(char, u32)],
}

/// Draw a sprite. `alpha < 1` blends glyph color over current bg.
pub fn draw(g: &mut Grid, spr: &Sprite, ox: i64, oy: i64, alpha: f64, tint: Option<Color>) {
    for (ry, row) in spr.rows.iter().enumerate() {
        let y = oy + ry as i64;
        for (rx, ch) in row.chars().enumerate() {
            if ch == ' ' {
                continue;
            }
            let color = match tint {
                Some(c) => c,
                None => match spr.pal.iter().find(|(k, _)| *k == ch) {
                    Some((_, hex)) => Color::hex(*hex),
                    None => continue,
                },
            };
            if alpha >= 1.0 {
                g.put(ox + rx as i64, y, ch, color);
            } else {
                g.put_alpha(ox + rx as i64, y, ch, color, alpha);
            }
        }
    }
}

pub fn sprite_size(spr: &Sprite) -> (i64, i64) {
    let w = spr
        .rows
        .iter()
        .map(|r| r.chars().count() as i64)
        .max()
        .unwrap_or(0);
    (w, spr.rows.len() as i64)
}

