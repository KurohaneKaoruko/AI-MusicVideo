/// Pop burst: radial sparks at (cx,cy), `p` = 0..1 life progress.
pub fn burst(g: &mut Grid, cx: i64, cy: i64, p: f64, color: Color) {
    let chars = ['*', '·', '°', '\'', '+'];
    for k in 0..10 {
        let a = k as f64 * std::f64::consts::PI / 5.0 + p;
        let d = 1.0 + p * 7.0;
        let x = cx + (a.cos() * d).round() as i64;
        let y = cy + (a.sin() * d * 0.55).round() as i64;
        g.put_alpha(x, y, chars[k % chars.len()], color, (1.0 - p).max(0.0) * 0.9);
    }
}
